<?php

declare(strict_types=1);

namespace App\Services\CompanyClosures;

use App\Enums\AbsenceRequestStatus;
use App\Models\AbsenceRequest;
use App\Models\CompanyClosure;
use App\Models\User;
use App\Services\Absences\Calendar\PersonNonWorkingDays;
use App\Services\Absences\Calendar\PersonWorkCalendar;
use App\Services\TimeEntries\DailyTargetResolver;
use Carbon\CarbonImmutable;
use Illuminate\Support\Collection;

/**
 * Generates the approved full-day absences of a collective leave closure (spec
 * 0304 D-15): one per active person with an employment profile to whom the
 * closure applies, skipping who already has a submitted/approved absence in
 * the period or no working day. Idempotent on the closure: the previously
 * generated requests are removed first. The caller owns the transaction.
 * Rows go in with one insert per chunk and no notification.
 */
final class CollectiveLeaveGenerator
{
    private const int INSERT_CHUNK = 500;

    public const string SKIP_OVERLAP = 'overlap';

    public const string SKIP_NO_WORKING_DAY = 'no_working_day';

    public function __construct(
        private readonly PersonWorkCalendar $calendar,
        private readonly DailyTargetResolver $dailyTarget,
    ) {}

    /**
     * @return array{created: int, skipped: list<array{user: array{id: int, name: string}, reason: string}>}
     */
    public function regenerate(CompanyClosure $closure, User $author): array
    {
        // Step 1: drop what the previous generation made
        $this->purge($closure);

        // Step 2: the people the closure applies to, and what stops each of them
        $people = $this->people($closure);
        $startsOn = $closure->starts_on->format('Y-m-d');
        $endsOn = $closure->ends_on->format('Y-m-d');
        $busy = $this->busyUserIds($people->modelKeys(), $startsOn, $endsOn);
        $days = $this->calendar->load($people->modelKeys(), $startsOn, $endsOn);

        // Step 3: one row per eligible person, a skip entry for the others
        $rows = [];
        $skipped = [];
        $now = now();

        foreach ($people as $person) {
            $workingDays = $this->workingDays($days, $person->id, $startsOn, $endsOn);
            $reason = isset($busy[$person->id]) ? self::SKIP_OVERLAP : ($workingDays === 0 ? self::SKIP_NO_WORKING_DAY : null);

            if ($reason !== null) {
                $skipped[] = ['user' => ['id' => $person->id, 'name' => $person->name], 'reason' => $reason];

                continue;
            }

            $rows[] = $this->row($closure, $person, $author, $workingDays, $now);
        }

        // Step 4: insert in blocks
        foreach (array_chunk($rows, self::INSERT_CHUNK) as $chunk) {
            AbsenceRequest::query()->insert($chunk);
        }

        return ['created' => count($rows), 'skipped' => $skipped];
    }

    /** Removes the requests generated by the closure (they are never edited by hand). */
    public function purge(CompanyClosure $closure): void
    {
        AbsenceRequest::query()->where('company_closure_id', $closure->id)->delete();
    }

    /**
     * @return Collection<int, User>
     */
    private function people(CompanyClosure $closure): Collection
    {
        $closure->loadMissing('operationalSites:id');

        $people = User::query()
            ->where('is_active', true)
            ->whereHas('employment')
            ->with('employment:id,user_id,standard_daily_minutes,break_daily_minutes')
            ->orderBy('name')
            ->orderBy('id')
            ->get(['id', 'name']);

        $sites = $this->calendar->siteIdsByUser($people->modelKeys());

        return $people->filter(fn (User $person): bool => $closure->appliesToSiteIds($sites[$person->id] ?? []))->values();
    }

    /**
     * @param  array<int, int>  $userIds
     * @return array<int, true> user ids with a submitted/approved request touching the period
     */
    private function busyUserIds(array $userIds, string $startsOn, string $endsOn): array
    {
        return AbsenceRequest::query()
            ->whereIn('user_id', $userIds)
            ->whereIn('status', [AbsenceRequestStatus::Submitted->value, AbsenceRequestStatus::Approved->value])
            ->where('starts_on', '<=', $endsOn)
            ->where('ends_on', '>=', $startsOn)
            ->distinct()
            ->pluck('user_id')
            ->mapWithKeys(static fn (int $id): array => [$id => true])
            ->all();
    }

    private function workingDays(PersonNonWorkingDays $days, int $userId, string $startsOn, string $endsOn): int
    {
        $count = 0;

        for ($day = CarbonImmutable::parse($startsOn); $day->format('Y-m-d') <= $endsOn; $day = $day->addDay()) {
            if (! $days->isNonWorkingDay($userId, $day->format('Y-m-d'))) {
                $count++;
            }
        }

        return $count;
    }

    /**
     * @return array<string, mixed>
     */
    private function row(CompanyClosure $closure, User $person, User $author, int $workingDays, mixed $now): array
    {
        return [
            'user_id' => $person->id,
            'absence_type_id' => $closure->absence_type_id,
            'created_by' => $author->id,
            'status' => AbsenceRequestStatus::Approved->value,
            'is_full_day' => true,
            'starts_on' => $closure->starts_on->format('Y-m-d'),
            'ends_on' => $closure->ends_on->format('Y-m-d'),
            'minutes' => $workingDays * $this->dailyTarget->resolve($person->employment),
            'is_short_notice' => false,
            'company_closure_id' => $closure->id,
            'decided_by' => $author->id,
            'decided_at' => $now,
            'submitted_at' => $now,
            'created_at' => $now,
            'updated_at' => $now,
        ];
    }
}
