<?php

declare(strict_types=1);

use App\Models\User;
use App\Notifications\WelcomeUserNotification;
use Illuminate\Support\Facades\Notification;

if (! function_exists('firstAccessPendingUser')) {
    /** A user flagged as pending first access, as UserOnboardingService::start() leaves it. */
    function firstAccessPendingUser(): User
    {
        $user = User::factory()->create();
        $user->forceFill(['must_set_password' => true])->save();

        return $user;
    }
}

if (! function_exists('firstAccessSentWelcome')) {
    /**
     * The WelcomeUserNotification sent to $user (Notification::fake() must be active),
     * or null when none was sent.
     */
    function firstAccessSentWelcome(User $user): ?WelcomeUserNotification
    {
        $sent = Notification::sent($user, WelcomeUserNotification::class);

        return $sent->last();
    }
}

if (! function_exists('firstAccessCreatePayload')) {
    /** A valid POST /api/users body (the password is generated by the system, spec 0355). */
    function firstAccessCreatePayload(array $overrides = []): array
    {
        return array_merge([
            'email' => 'new.person@example.com',
            'locale' => 'it',
            'personal_data' => individualProfile(),
            'employment' => ['covers_all_product_categories' => true, 'business_function_ids' => [membershipFunctionId()]],
        ], $overrides);
    }
}

if (! function_exists('configDefaultUnderEnvironment')) {
    /**
     * Evaluates config/{$file}.php with the given APP_ENV and the $override env
     * variable unset, and returns its $key: the environment default of a flag.
     */
    function configDefaultUnderEnvironment(string $file, string $key, string $override, string $environment): mixed
    {
        $saved = [$_SERVER['APP_ENV'] ?? null, $_ENV['APP_ENV'] ?? null, getenv('APP_ENV')];

        try {
            $_SERVER['APP_ENV'] = $_ENV['APP_ENV'] = $environment;
            putenv("APP_ENV={$environment}");
            unset($_SERVER[$override], $_ENV[$override]);
            putenv($override);

            return (require config_path("{$file}.php"))[$key];
        } finally {
            [$_SERVER['APP_ENV'], $_ENV['APP_ENV']] = [$saved[0], $saved[1]];
            putenv($saved[2] === false ? 'APP_ENV' : "APP_ENV={$saved[2]}");
        }
    }
}
